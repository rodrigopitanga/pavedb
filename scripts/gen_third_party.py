"""Regenerate THIRD_PARTY_LICENSES.md from the runtime dependency closure.

The closure is what a default ``pip install .`` resolves (no test/dev extras),
obtained from a ``pip install . --dry-run --report`` JSON. Each third-party
package is bucketed by an SPDX-ish license signal; an unrecognized signal falls
to ``manual_review`` rather than being assumed permissive.

The doc tracks external resolution (pip picks the latest compatible versions),
so it is a point-in-time visibility reference, not a drift-gated snapshot like
the code-derived reference docs. Refresh it with ``make third-party-licenses``.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.md"

# The project itself is not third-party; it appears in its own report as the
# requested root. Its license is stated in the header instead.
ROOT_PROJECT = "pavedb"

# Weak/strong copyleft SPDX tokens. Matching is generous on purpose: an
# over-flag lands in a human-reviewed bucket (safe); a missed copyleft silently
# called "permissive" is the only dangerous error.
COPYLEFT = (
    "gpl", "agpl", "lgpl", "mpl", "epl", "cddl", "ms-pl", "eupl", "cecill",
    "osl-", "sleepycat", "cpal", "cc-by-sa",
)
# Clear permissive SPDX tokens. Only these earn "permissive"; anything else is
# manual_review.
PERMISSIVE = (
    "mit", "bsd", "apache", "isc", "psf", "python-2.0", "python software",
    "zlib", "0bsd", "cc0", "unlicense", "wtfpl", "postgresql", "ncsa",
    "boost", "bsl-1.0", "cnri", "hpnd",
)

BUCKET_ORDER = (
    "copyleft_or_weak_copyleft",
    "manual_review",
    "permissive_or_other",
)


def project_version() -> str:
    ns: dict[str, object] = {}
    exec((ROOT / "pave" / "version.py").read_text(encoding="utf-8"), ns)
    return str(ns.get("VERSION", "0.0.0"))


def _signals(md: dict) -> tuple[str, str, list[str]]:
    expr = (md.get("license_expression") or "").strip()
    lic = (md.get("license") or "").strip()
    classifiers = [c for c in md.get("classifier", []) if c.startswith("License")]
    return expr, lic, classifiers


def bucket(expr: str, lic: str, classifiers: list[str]) -> str:
    """Classify on structured signals; only short license strings are trusted.

    A long ``license`` field is the full license *text* (e.g. scipy ships
    ~47 KB), which embeds bundled-component notices that token-matching would
    misread — so it is ignored for classification past 60 chars.
    """
    parts = [expr, *classifiers]
    if 0 < len(lic) <= 60:
        parts.append(lic)
    hay = " ".join(parts).lower()
    if any(tok in hay for tok in COPYLEFT):
        return "copyleft_or_weak_copyleft"
    if any(tok in hay for tok in PERMISSIVE):
        return "permissive_or_other"
    return "manual_review"


def _cell(value: str) -> str:
    """Make a string safe for a one-line Markdown table cell."""
    value = value.replace("\n", " ").replace("|", "\\|").strip()
    return value or "-"


def _short_license(lic: str) -> str:
    first = lic.splitlines()[0].strip() if lic else ""
    return (first[:57] + "...") if len(first) > 60 else first


def _resolve_installs(report: Path | None) -> list[dict]:
    if report is None:
        with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp:
            report = Path(tmp.name)
        subprocess.run(
            [sys.executable, "-m", "pip", "install", str(ROOT), "--dry-run",
             "--ignore-installed", "--quiet", "--report", str(report)],
            check=True,
        )
    return json.loads(report.read_text(encoding="utf-8")).get("install", [])


def render(installs: list[dict], version: str) -> str:
    rows = []
    for entry in installs:
        md = entry.get("metadata", {})
        name = md.get("name", "")
        if name.lower() == ROOT_PROJECT and entry.get("requested"):
            continue
        expr, lic, classifiers = _signals(md)
        rows.append({
            "name": name,
            "version": md.get("version", ""),
            "expr": expr,
            "lic": lic,
            "classifiers": classifiers,
            "category": bucket(expr, lic, classifiers),
        })
    rows.sort(key=lambda r: r["name"].lower())
    counts = {b: sum(1 for r in rows if r["category"] == b) for b in BUCKET_ORDER}

    out: list[str] = []
    out.append("<!-- (C) 2026 Rodrigo Rodrigues da Silva <rodrigo@flowlexi.com> -->")
    out.append("<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->")
    out.append("")
    out.append("# Third-Party Licenses")
    out.append("")
    out.append(
        "Generated by `scripts/gen_third_party.py` from the CPU runtime "
        "dependency closure — the packages `pip install .` resolves without "
        "CUDA, test, or dev extras. The `-cpu` image carries only these; the "
        "`-cuda` image additionally bundles NVIDIA's proprietary CUDA "
        "runtime (see the binary-wheel note). For dependency-license "
        "visibility only; an engineering audit, not legal advice."
    )
    out.append("")
    out.append(
        f"- Source: CPU runtime closure for PaveDB `{version}` "
        f"(resolved by pip, {len(rows)} third-party packages)"
    )
    out.append("- Project license: `AGPL-3.0-or-later` (PaveDB)")
    out.append("")
    out.append("## Summary")
    out.append("")
    for b in BUCKET_ORDER:
        out.append(f"- `{b}`: {counts[b]}")
    out.append("")

    def signal_table(category: str, heading: str) -> None:
        out.append(f"## {heading}")
        out.append("")
        picked = [r for r in rows if r["category"] == category]
        if not picked:
            out.append("_None._")
            out.append("")
            return
        out.append("| Package | Version | License |")
        out.append("|---|---:|---|")
        for r in picked:
            signal = r["expr"] or _short_license(r["lic"]) or " | ".join(r["classifiers"])
            out.append(f"| {_cell(r['name'])} | {_cell(r['version'])} | {_cell(signal)} |")
        out.append("")

    signal_table("copyleft_or_weak_copyleft", "Copyleft / Weak Copyleft")
    signal_table("manual_review", "Manual Review")

    out.append(
        "**Binary wheels.** Some wheels (e.g. `torch`, `scipy`, `numpy`, "
        "`faiss-cpu`) bundle third-party runtime components (BLAS/LAPACK, "
        "compiler runtimes) under their own licenses. The `-cpu` image carries "
        "none of NVIDIA's CUDA stack; the `-cuda` image, published "
        "best-effort for final releases, additionally pulls "
        "torch's Linux-only CUDA dependencies — the `nvidia-*` runtimes "
        "(NVIDIA proprietary) and `triton` (MIT). Distributed images keep each "
        "package's `*.dist-info` directory (license/NOTICE files) so those "
        "terms travel with the binaries."
    )
    out.append("")
    out.append("## Full Inventory")
    out.append("")
    out.append(
        "| Package | Version | License-Expression | License | "
        "License Classifiers | Category |"
    )
    out.append("|---|---:|---|---|---|---|")
    for r in rows:
        out.append(
            f"| {_cell(r['name'])} | {_cell(r['version'])} | {_cell(r['expr'])} "
            f"| {_cell(_short_license(r['lic']))} "
            f"| {_cell(' | '.join(r['classifiers']))} | {r['category']} |"
        )
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--report", type=Path, default=None,
        help="reuse an existing `pip install --report` JSON instead of resolving",
    )
    parser.add_argument(
        "--stdout", action="store_true",
        help="write to stdout instead of THIRD_PARTY_LICENSES.md",
    )
    args = parser.parse_args(argv)

    installs = _resolve_installs(args.report)
    rendered = render(installs, project_version())
    if args.stdout:
        sys.stdout.write(rendered)
    else:
        OUTPUT.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
